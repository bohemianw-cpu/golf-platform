-- 읽기 전용: 마이그레이션 밖(대시보드)에서 만든 기존 객체의 현재 정의를 DDL 문자열로 출력한다.
-- Supabase SQL Editor에서 실행한 뒤 결과의 ddl 칸 하나를 그대로 복사해 기준 마이그레이션 작성에 사용한다.
-- 데이터는 읽지 않고 시스템 카탈로그만 조회한다.
with target(name) as (
  values ('profiles'), ('rounds'), ('round_holes'), ('round_shots'), ('user_clubs'), ('lesson_inquiries')
),
rel as (
  select c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity
  from pg_catalog.pg_class c
  join pg_catalog.pg_namespace n on n.oid = c.relnamespace
  join target t on t.name = c.relname
  where n.nspname = 'public' and c.relkind in ('r', 'p')
),
tables as (
  select 10 as section, r.relname::text as sort_key,
    format(E'create table public.%I (\n%s\n);', r.relname, string_agg(
      format('  %I %s%s%s', a.attname, pg_catalog.format_type(a.atttypid, a.atttypmod),
        case a.attidentity when 'a' then ' generated always as identity'
          when 'd' then ' generated by default as identity' else '' end
        || case when a.attgenerated = 's' then ' generated always as (' || pg_catalog.pg_get_expr(d.adbin, d.adrelid) || ') stored'
          when d.adbin is not null then ' default ' || pg_catalog.pg_get_expr(d.adbin, d.adrelid) else '' end,
        case when a.attnotnull then ' not null' else '' end),
      E',\n' order by a.attnum)) as ddl
  from rel r
  join pg_catalog.pg_attribute a on a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped
  left join pg_catalog.pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
  group by r.relname
),
constraints as (
  -- 기본키·고유·검사 제약을 먼저, 외래키를 나중에 출력한다.
  select case when con.contype = 'f' then 30 else 20 end, r.relname || '.' || con.conname,
    format('alter table public.%I add constraint %I %s;', r.relname, con.conname, pg_catalog.pg_get_constraintdef(con.oid))
  from rel r join pg_catalog.pg_constraint con on con.conrelid = r.oid
  where con.contype in ('p', 'u', 'c', 'f', 'x')
),
indexes as (
  select 40, r.relname || '.' || i.relname, pg_catalog.pg_get_indexdef(i.oid) || ';'
  from rel r
  join pg_catalog.pg_index x on x.indrelid = r.oid
  join pg_catalog.pg_class i on i.oid = x.indexrelid
  where not exists (select 1 from pg_catalog.pg_constraint con where con.conindid = i.oid)
),
rls as (
  select 50, r.relname::text,
    format('alter table public.%I enable row level security;', r.relname)
    || case when r.relforcerowsecurity then format(E'\nalter table public.%I force row level security;', r.relname) else '' end
  from rel r where r.relrowsecurity
),
policies as (
  select 60, p.tablename || '.' || p.policyname,
    format('create policy %I on public.%I as %s for %s to %s%s%s;', p.policyname, p.tablename,
      lower(p.permissive), lower(p.cmd), array_to_string(p.roles, ', '),
      coalesce(E'\n  using (' || p.qual || ')', ''),
      coalesce(E'\n  with check (' || p.with_check || ')', ''))
  from pg_catalog.pg_policies p join target t on t.name = p.tablename
  where p.schemaname = 'public'
),
grants as (
  select 70, g.table_name || '.' || g.grantee,
    format('grant %s on public.%I to %I;', string_agg(lower(g.privilege_type), ', ' order by g.privilege_type), g.table_name, g.grantee)
  from information_schema.role_table_grants g join target t on t.name = g.table_name
  where g.table_schema = 'public' and g.grantee in ('anon', 'authenticated', 'service_role')
  group by g.table_name, g.grantee
),
functions as (
  -- 마이그레이션에서 참조만 하는 함수와, 대상 테이블·auth.users 트리거가 호출하는 함수.
  select 80, n.nspname || '.' || p.proname, pg_catalog.pg_get_functiondef(p.oid) || ';'
  from pg_catalog.pg_proc p
  join pg_catalog.pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind = 'f'
    and (p.proname in ('handle_new_user', 'is_admin')
      or p.oid in (
        select tg.tgfoid from pg_catalog.pg_trigger tg
        where not tg.tgisinternal
          and (tg.tgrelid in (select oid from rel) or tg.tgrelid = pg_catalog.to_regclass('auth.users'))))
),
triggers as (
  select 90, tg.tgrelid::regclass::text || '.' || tg.tgname, pg_catalog.pg_get_triggerdef(tg.oid) || ';'
  from pg_catalog.pg_trigger tg
  where not tg.tgisinternal
    and (tg.tgrelid in (select oid from rel) or tg.tgrelid = pg_catalog.to_regclass('auth.users'))
),
all_ddl(section, sort_key, ddl) as (
  select * from tables union all select * from constraints union all select * from indexes
  union all select * from rls union all select * from policies union all select * from grants
  union all select * from functions union all select * from triggers
)
select string_agg(ddl, E'\n\n' order by section, sort_key) as ddl from all_ddl;
